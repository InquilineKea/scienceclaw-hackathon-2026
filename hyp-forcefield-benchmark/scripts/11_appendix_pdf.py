"""Step 10: render the code and every text result into one PDF (for hosts that refuse .zip, e.g. WordPress.com).

Binary outputs (trajectories md/*.npz, results/md_distributions.npz, figures) are listed with SHA-256 but not
rendered.  Output: hyp_benchmark_appendix.pdf
"""
import glob
import hashlib
import json
import os
import sys
import textwrap

from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import PageBreak, Paragraph, Preformatted, SimpleDocTemplate, Spacer

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "hyp_benchmark_appendix.pdf")
WIDTH = 150

ss = getSampleStyleSheet()
H1 = ParagraphStyle("h1", parent=ss["Heading1"], fontSize=15)
H2 = ParagraphStyle("h2", parent=ss["Heading2"], fontSize=11, spaceBefore=6)
BODY = ParagraphStyle("b", parent=ss["BodyText"], fontSize=8.5, leading=11)
CODE = ParagraphStyle("c", fontName="Courier", fontSize=6.2, leading=7.3)


def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def wrap(text):
    out = []
    for line in text.splitlines():
        line = line.replace("\t", "    ")
        if len(line) <= WIDTH:
            out.append(line)
        else:
            out += textwrap.wrap(line, WIDTH, subsequent_indent="  ↪ ", break_long_words=True, replace_whitespace=False) or [""]
    return "\n".join(out)


def compact_json(path):
    """One record per line for list-like JSON; pretty but compact for dicts."""
    if path.endswith(".jsonl"):
        return open(path).read()
    d = json.load(open(path))

    def dump(x, ind=0):
        pad = "  " * ind
        if isinstance(x, dict) and all(not isinstance(v, (dict, list)) or len(json.dumps(v)) < 40 for v in x.values()):
            return json.dumps({k: (round(v, 6) if isinstance(v, float) else v) for k, v in x.items()}, separators=(",", ":"), default=str)
        if isinstance(x, dict) and len(json.dumps(x)) > WIDTH - len(pad):
            return "{\n" + ",\n".join(f"{pad}  {json.dumps(k)}: {dump(v, ind + 1)}" for k, v in x.items()) + f"\n{pad}}}"
        if isinstance(x, list) and len(json.dumps(x)) > WIDTH - len(pad) and any(isinstance(e, (dict, list)) for e in x):
            return "[\n" + ",\n".join(f"{pad}  {dump(v, ind + 1)}" for v in x) + f"\n{pad}]"
        return json.dumps(x, separators=(",", ":"), default=str)

    return dump(d)


story = [Paragraph("Hydroxyproline force-field benchmark: data and code appendix", H1),
         Paragraph("Generated by scripts/11_appendix_pdf.py. Every text file of the benchmark is reproduced below verbatim "
                   "(JSON re-indented for width; long lines wrapped and marked ↪). Binary files are listed with SHA-256 "
                   "in the manifest but not rendered. Contents: README, status ledger, manifest, results, library, scripts, tests.", BODY),
         Spacer(1, 4 * mm)]

sections = [("README.md", ["README.md"]), ("Status ledger", ["STATUS.md"])]
binaries = sorted(glob.glob(os.path.join(ROOT, "md", "*", "*"))) + [os.path.join(ROOT, "results", "md_distributions.npz")] + \
    sorted(glob.glob(os.path.join(ROOT, "figs", "*.png"))) + sorted(glob.glob(os.path.join(ROOT, "structures", "*.pdb")))
derived = sorted(glob.glob(os.path.join(ROOT, "ff", "derived", "*")))
manifest = "\n".join(f"{sha(p)}  {os.path.relpath(p, ROOT)}  ({os.path.getsize(p)} bytes)" for p in binaries + derived)

results = sorted(glob.glob(os.path.join(ROOT, "results", "*.json")) + glob.glob(os.path.join(ROOT, "results", "*.jsonl")))
code = sorted(glob.glob(os.path.join(ROOT, "hypbench", "*.py"))) + sorted(glob.glob(os.path.join(ROOT, "scripts", "*.py"))) + \
    sorted(glob.glob(os.path.join(ROOT, "scripts", "*.sh"))) + sorted(glob.glob(os.path.join(ROOT, "tests", "*.py")))

for title, files in sections:
    story.append(Paragraph(title, H2))
    for f in files:
        story.append(Preformatted(wrap(open(os.path.join(ROOT, f)).read()), CODE))
story += [Paragraph("Manifest of binary and derived files (SHA-256)", H2), Preformatted(wrap(manifest), CODE), PageBreak()]
story.append(Paragraph("Results", H1))
for p in results:
    story += [Paragraph(f"results/{os.path.basename(p)}  ·  sha256 {sha(p)[:16]}…", H2), Preformatted(wrap(compact_json(p)), CODE)]
story += [PageBreak(), Paragraph("Code", H1)]
for p in code:
    story += [Paragraph(f"{os.path.relpath(p, ROOT)}  ·  sha256 {sha(p)[:16]}…", H2), Preformatted(wrap(open(p).read()), CODE)]
for p in sorted(glob.glob(os.path.join(ROOT, "structures", "*.pdb"))):
    story += [Paragraph(os.path.relpath(p, ROOT), H2), Preformatted(open(p).read(), CODE)]


def footer(c, doc):
    c.setFont("Helvetica", 7)
    c.drawRightString(A4[0] - 12 * mm, 8 * mm, f"Hyp force-field benchmark appendix · page {doc.page}")


SimpleDocTemplate(OUT, pagesize=A4, leftMargin=10 * mm, rightMargin=10 * mm, topMargin=12 * mm, bottomMargin=14 * mm,
                  title="Hydroxyproline force-field benchmark: data and code appendix").build(story, onFirstPage=footer, onLaterPages=footer)
print(OUT, os.path.getsize(OUT), "bytes")
